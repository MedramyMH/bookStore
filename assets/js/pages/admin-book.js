// Admin: create / edit a book (upload PDF, cover, auto-generate cover + free sample)
import { CONFIG } from "../config.js";
import { t, tr, LANG_NAMES } from "../i18n.js";
import { esc, icon, toast, setTitle, slugify, formatBytes, coverHTML, confirmDialog } from "../ui.js";
import {
  getBookById, getCategories, adminSaveBook, adminUpload, adminDownloadBookBytes, adminCleanOldFiles, adminDeleteBook,
} from "../api.js";

const CURRENCIES = ["USD", "EUR", "GBP", "CAD", "AUD", "CHF"]; // PayPal-supported
const MAX_MB = 50; // Supabase free plan limit per file

export default async function render({ root, params, isCurrent }) {
  const isNew = params.id === "new";
  const [existing, categories] = await Promise.all([
    isNew ? null : getBookById(params.id),
    getCategories().catch(() => []),
  ]);
  if (!isCurrent()) return;
  if (!isNew && !existing) { root.innerHTML = `<div class="container narrow"><p>${esc(t("bookNotFound"))}</p></div>`; return; }

  const b = existing || {
    id: crypto.randomUUID(), language: "ar", price: 0, currency: CONFIG.DEFAULT_CURRENCY, sample_pages: 10,
    allow_download: true, is_published: true, is_featured: false, author: tr(CONFIG.AUTHOR_NAME), tags: [],
  };
  setTitle(isNew ? t("addBook") : t("editBook"));

  let pdfFile = null;     // File selected by admin
  let pdfDoc = null;      // pdf.js document of selected file
  let coverBlob = null;   // new cover to upload
  let pageCount = b.page_count || null;

  root.innerHTML = `
  <div class="container admin-edit">
    <nav class="breadcrumb"><a href="#/admin?tab=books">${esc(t("navAdmin"))}</a> <span>/</span> <span>${esc(isNew ? t("addBook") : t("editBook"))}</span></nav>
    <h1>${esc(isNew ? t("addBook") : t("editBook"))}</h1>

    <form id="book-form" class="edit-grid" novalidate>
      <div class="edit-main stack">
        <section class="card stack">
          <h3>${icon("file")} ${esc(t("bookFile"))}</h3>
          <label class="dropzone" id="pdf-drop">
            <input type="file" accept="application/pdf,.pdf" id="pdf-input" hidden />
            ${icon("upload")}
            <strong id="pdf-label">${esc(b.file_path ? t("replacePdf") : t("choosePdf"))}</strong>
            <span class="muted small" id="pdf-info">${b.file_path ? esc(`${t("currentFile")}: ${b.page_count || "?"} ${t("pages")} · ${formatBytes(b.file_size)}`) : esc(t("pdfHint", { mb: MAX_MB }))}</span>
          </label>
        </section>

        <section class="card stack">
          <h3>${esc(t("details"))}</h3>
          <div class="grid-2">
            <label class="field span-2"><span>${esc(t("title"))} *</span><input class="input" name="title" required value="${esc(b.title || "")}" dir="auto" /></label>
            <label class="field span-2"><span>${esc(t("subtitle"))}</span><input class="input" name="subtitle" value="${esc(b.subtitle || "")}" dir="auto" /></label>
            <label class="field"><span>${esc(t("author"))} *</span><input class="input" name="author" required value="${esc(b.author || "")}" dir="auto" /></label>
            <label class="field"><span>${esc(t("bookLanguage"))} *</span>
              <select class="input" name="language">${["ar", "en", "fr"].map((l) => `<option value="${l}" ${b.language === l ? "selected" : ""}>${LANG_NAMES[l]}</option>`).join("")}</select></label>
            <label class="field"><span>${esc(t("category"))}</span><input class="input" name="category" list="cat-list" value="${esc(b.category || "")}" dir="auto" />
              <datalist id="cat-list">${categories.map((c) => `<option value="${esc(c)}">`).join("")}</datalist></label>
            <label class="field"><span>${esc(t("tags"))}</span><input class="input" name="tags" value="${esc((b.tags || []).join(", "))}" placeholder="${esc(t("tagsHint"))}" dir="auto" /></label>
            <label class="field span-2"><span>${esc(t("description"))}</span><textarea class="input" name="description" rows="8" dir="auto">${esc(b.description || "")}</textarea></label>
            <label class="field"><span>${esc(t("publisher"))}</span><input class="input" name="publisher" value="${esc(b.publisher || "")}" dir="auto" /></label>
            <label class="field"><span>${esc(t("year"))}</span><input class="input" type="number" name="published_year" min="1000" max="2100" value="${esc(b.published_year || "")}" /></label>
            <label class="field"><span>ISBN</span><input class="input" name="isbn" value="${esc(b.isbn || "")}" dir="ltr" /></label>
            <label class="field"><span>${esc(t("urlSlug"))}</span><input class="input" name="slug" value="${esc(b.slug || "")}" placeholder="${esc(t("autoGenerated"))}" dir="ltr" /></label>
          </div>
        </section>
      </div>

      <aside class="edit-side stack">
        <section class="card stack">
          <h3>${esc(t("cover"))}</h3>
          <div class="cover-preview" id="cover-preview">${coverHTML({ ...b, title: b.title || t("title") })}</div>
          <label class="btn btn-ghost btn-sm btn-block">${icon("upload")} ${esc(t("uploadCover"))}
            <input type="file" accept="image/*" id="cover-input" hidden /></label>
          <button type="button" class="btn btn-ghost btn-sm btn-block" id="cover-from-pdf">${icon("file")} ${esc(t("coverFromPdf"))}</button>
          <p class="muted small">${esc(t("coverHint"))}</p>
        </section>

        <section class="card stack">
          <h3>${esc(t("pricing"))}</h3>
          <div class="seg" role="radiogroup">
            <label><input type="radio" name="pricing" value="free" ${!Number(b.price) ? "checked" : ""}/> <span>${esc(t("free"))}</span></label>
            <label><input type="radio" name="pricing" value="paid" ${Number(b.price) ? "checked" : ""}/> <span>${esc(t("paid"))}</span></label>
          </div>
          <div class="paid-only grid-2">
            <label class="field"><span>${esc(t("price"))}</span><input class="input" type="number" name="price" min="0.5" step="0.01" value="${Number(b.price) || ""}" dir="ltr" /></label>
            <label class="field"><span>${esc(t("currency"))}</span><select class="input" name="currency">${CURRENCIES.map((c) => `<option ${b.currency === c ? "selected" : ""}>${c}</option>`).join("")}</select></label>
            <label class="field span-2"><span>${esc(t("samplePages"))}</span><input class="input" type="number" name="sample_pages" min="0" max="100" value="${b.sample_pages ?? 10}" />
              <small class="muted">${esc(t("samplePagesHint"))}</small></label>
          </div>
        </section>

        <section class="card stack">
          <h3>${esc(t("visibility"))}</h3>
          <label class="switch"><input type="checkbox" name="is_published" ${b.is_published ? "checked" : ""}/><span></span> ${esc(t("published"))}</label>
          <label class="switch"><input type="checkbox" name="is_featured" ${b.is_featured ? "checked" : ""}/><span></span> ${esc(t("featured"))}</label>
          <label class="switch"><input type="checkbox" name="allow_download" ${b.allow_download ? "checked" : ""}/><span></span> ${esc(t("allowDownload"))}</label>
        </section>

        <div class="save-box card stack">
          <ul class="steps" id="save-steps" hidden></ul>
          <button class="btn btn-primary btn-lg btn-block" type="submit" id="save-btn">${icon("check")} ${esc(t("saveBook"))}</button>
          ${!isNew ? `<a class="btn btn-ghost btn-block" href="#/book/${encodeURIComponent(b.slug)}">${icon("eye")} ${esc(t("viewPage"))}</a>
            <button type="button" class="btn btn-danger-ghost btn-block" id="delete-btn">${icon("trash")} ${esc(t("delete"))}</button>` : ""}
        </div>
      </aside>
    </form>
  </div>`;

  const form = root.querySelector("#book-form");
  const $f = (n) => form.elements[n];
  const preview = root.querySelector("#cover-preview");

  // ---------- pricing toggle
  const syncPricing = () => form.classList.toggle("is-free", form.querySelector('[name="pricing"]:checked').value === "free");
  form.querySelectorAll('[name="pricing"]').forEach((r) => (r.onchange = syncPricing));
  syncPricing();

  // ---------- PDF select (click or drag & drop)
  const drop = root.querySelector("#pdf-drop");
  const pdfInput = root.querySelector("#pdf-input");
  ["dragover", "dragenter"].forEach((ev) => drop.addEventListener(ev, (e) => { e.preventDefault(); drop.classList.add("over"); }));
  ["dragleave", "drop"].forEach((ev) => drop.addEventListener(ev, () => drop.classList.remove("over")));
  drop.addEventListener("drop", (e) => { e.preventDefault(); const f = e.dataTransfer.files[0]; if (f) selectPdf(f); });
  pdfInput.onchange = () => pdfInput.files[0] && selectPdf(pdfInput.files[0]);

  async function selectPdf(file) {
    if (file.type !== "application/pdf" && !file.name.toLowerCase().endsWith(".pdf")) { toast(t("errNotPdf"), "error"); return; }
    if (file.size > MAX_MB * 1024 * 1024) toast(t("warnLargeFile", { mb: MAX_MB }), "error", 7000);
    pdfFile = file;
    root.querySelector("#pdf-label").textContent = file.name;
    root.querySelector("#pdf-info").textContent = `${formatBytes(file.size)} · ${t("reading")}…`;
    try {
      const { openPdf } = await import("../pdf.js");
      pdfDoc = await openPdf(new Uint8Array(await file.arrayBuffer()));
      pageCount = pdfDoc.numPages;
      root.querySelector("#pdf-info").textContent = `${formatBytes(file.size)} · ${pageCount} ${t("pages")}`;
      // Prefill title from PDF metadata
      const meta = await pdfDoc.getMetadata().catch(() => null);
      const metaTitle = String(meta?.info?.Title || "").trim();
      const junk = /^(about:|untitled|sans titre|document\d*$)|microsoft (word|powerpoint)|\.(docx?|pdf|odt|indd)$/i;
      if (!$f("title").value && metaTitle && !junk.test(metaTitle)) $f("title").value = metaTitle;
      if (!b.cover_url && !coverBlob) await makeCoverFromPdf();
    } catch (e) {
      console.error(e);
      root.querySelector("#pdf-info").textContent = t("errReadPdf");
      pdfDoc = null;
    }
  }

  // ---------- cover
  async function makeCoverFromPdf() {
    try {
      const { openPdf, firstPageToJpeg } = await import("../pdf.js");
      if (!pdfDoc) {
        if (!b.file_path) { toast(t("choosePdfFirst"), "error"); return; }
        pdfDoc = await openPdf(await adminDownloadBookBytes(b.file_path));
      }
      coverBlob = await firstPageToJpeg(pdfDoc, 800);
      showCover(URL.createObjectURL(coverBlob));
    } catch (e) { toast(e.message, "error"); }
  }
  function showCover(src) { preview.innerHTML = `<img class="cover" src="${esc(src)}" alt="" />`; }

  root.querySelector("#cover-from-pdf").onclick = makeCoverFromPdf;
  root.querySelector("#cover-input").onchange = async (e) => {
    const f = e.target.files[0]; if (!f) return;
    coverBlob = await resizeImage(f, 900);
    showCover(URL.createObjectURL(coverBlob));
  };

  // ---------- delete
  root.querySelector("#delete-btn")?.addEventListener("click", async () => {
    if (!(await confirmDialog(t("deleteBookConfirm", { title: b.title }), { danger: true, okText: t("delete") }))) return;
    await adminDeleteBook(b); toast(t("deleted"), "success"); location.hash = "#/admin?tab=books";
  });

  // ---------- save
  const stepsEl = root.querySelector("#save-steps");
  const step = (label) => {
    stepsEl.hidden = false;
    stepsEl.querySelectorAll("li.doing").forEach((li) => li.className = "done");
    const li = document.createElement("li"); li.className = "doing"; li.textContent = label; stepsEl.appendChild(li);
  };

  form.onsubmit = async (e) => {
    e.preventDefault();
    const title = $f("title").value.trim();
    const author = $f("author").value.trim();
    if (!title || !author) { toast(t("errRequired"), "error"); $f(title ? "author" : "title").focus(); return; }
    if (isNew && !pdfFile) { toast(t("choosePdfFirst"), "error"); return; }
    const paid = form.querySelector('[name="pricing"]:checked').value === "paid";
    const price = paid ? Number($f("price").value) : 0;
    if (paid && !(price > 0)) { toast(t("errPrice"), "error"); $f("price").focus(); return; }

    const btn = root.querySelector("#save-btn");
    btn.disabled = true; stepsEl.innerHTML = "";
    const ts = Date.now();
    try {
      const row = {
        id: b.id,
        slug: ($f("slug").value.trim() || b.slug || slugify(title)).replace(/\s+/g, "-"),
        title, author,
        subtitle: $f("subtitle").value.trim() || null,
        language: $f("language").value,
        category: $f("category").value.trim(),
        tags: $f("tags").value.split(",").map((s) => s.trim()).filter(Boolean),
        description: $f("description").value.trim(),
        publisher: $f("publisher").value.trim() || null,
        published_year: Number($f("published_year").value) || null,
        isbn: $f("isbn").value.trim() || null,
        price,
        currency: $f("currency").value,
        sample_pages: Number($f("sample_pages").value) || 0,
        is_published: $f("is_published").checked,
        is_featured: $f("is_featured").checked,
        allow_download: $f("allow_download").checked,
        page_count: pageCount,
        file_path: b.file_path || null,
        file_size: b.file_size || null,
        cover_url: b.cover_url || null,
        sample_url: b.sample_url || null,
      };

      let pdfBytes = null;
      if (pdfFile) {
        step(t("stepUploadPdf"));
        pdfBytes = new Uint8Array(await pdfFile.arrayBuffer());
        row.file_path = await adminUpload("books", `${b.id}/book-${ts}.pdf`, pdfFile, "application/pdf");
        row.file_size = pdfFile.size;
      }

      if (!coverBlob && !row.cover_url) {
        step(t("stepCover"));
        await makeCoverFromPdf();
      }
      if (coverBlob) {
        step(t("stepUploadCover"));
        row.cover_url = await adminUpload("covers", `${b.id}/cover-${ts}.jpg`, coverBlob, "image/jpeg");
      }

      const needSample = paid && row.sample_pages > 0 &&
        (pdfFile || !row.sample_url || row.sample_pages !== b.sample_pages);
      if (needSample) {
        step(t("stepSample"));
        if (!pdfBytes) pdfBytes = await adminDownloadBookBytes(row.file_path);
        const sample = await buildSample(pdfBytes, row.sample_pages, title);
        row.sample_url = await adminUpload("samples", `${b.id}/sample-${ts}.pdf`, new Blob([sample], { type: "application/pdf" }), "application/pdf");
      }
      if (!paid || !row.sample_pages) row.sample_url = null;

      step(t("stepSaving"));
      const saved = await adminSaveBook(row);

      step(t("stepCleanup"));
      await Promise.all([
        pdfFile ? adminCleanOldFiles("books", b.id, row.file_path) : null,
        coverBlob ? adminCleanOldFiles("covers", b.id, row.cover_url.split("/covers/")[1]?.split("?")[0]) : null,
        needSample || !row.sample_url ? adminCleanOldFiles("samples", b.id, row.sample_url ? row.sample_url.split("/samples/")[1] : null) : null,
      ]).catch(() => {});

      stepsEl.querySelectorAll("li").forEach((li) => (li.className = "done"));
      toast(t("bookSaved"), "success");
      location.hash = `#/book/${encodeURIComponent(saved.slug)}`;
    } catch (err) {
      console.error(err);
      stepsEl.querySelector("li.doing")?.classList.replace("doing", "failed");
      toast(/duplicate key.*slug/i.test(err.message) ? t("errSlugTaken") : err.message, "error", 7000);
    } finally { btn.disabled = false; }
  };
}

/** First N pages → new PDF (Uint8Array) with pdf-lib */
async function buildSample(bytes, pages, title) {
  const { PDFDocument } = await import("pdf-lib");
  const src = await PDFDocument.load(bytes, { ignoreEncryption: true });
  const out = await PDFDocument.create();
  const n = Math.min(pages, src.getPageCount());
  const copied = await out.copyPages(src, [...Array(n).keys()]);
  copied.forEach((p) => out.addPage(p));
  out.setTitle(`${title} — sample`);
  return out.save();
}

function resizeImage(file, maxW) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      const scale = Math.min(1, maxW / img.width);
      const c = document.createElement("canvas");
      c.width = Math.round(img.width * scale); c.height = Math.round(img.height * scale);
      const ctx = c.getContext("2d");
      ctx.fillStyle = "#fff"; ctx.fillRect(0, 0, c.width, c.height);
      ctx.drawImage(img, 0, 0, c.width, c.height);
      c.toBlob((bl) => (bl ? resolve(bl) : reject(new Error("image"))), "image/jpeg", 0.88);
      URL.revokeObjectURL(img.src);
    };
    img.onerror = reject;
    img.src = URL.createObjectURL(file);
  });
}
